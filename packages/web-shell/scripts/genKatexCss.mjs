// Generates a self-contained KaTeX stylesheet (CSS + embedded woff2 fonts) from the
// installed `katex` dependency, so the canvas, the measurer, and the exported/printed
// deck all render math fully offline — no CDN, no external font files. This is what
// makes the `renderMath` seam's output portable (matches the project's self-contained,
// CSP-safe stance). Regenerate after upgrading katex:  node scripts/genKatexCss.mjs
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const require = createRequire(import.meta.url)
const cssPath = require.resolve('katex/dist/katex.min.css') // resolves through pnpm symlinks
const distDir = path.dirname(cssPath)
const fontsDir = path.join(distDir, 'fonts')
const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'katexInlineCss.ts',
)

let css = readFileSync(cssPath, 'utf8')

// 1. Drop the woff/ttf alternatives — every browser we target supports woff2.
css = css.replace(
  /,url\(fonts\/[\w-]+\.woff\) format\("woff"\),url\(fonts\/[\w-]+\.ttf\) format\("truetype"\)/g,
  '',
)

// 2. Inline each remaining woff2 reference as a base64 data URI.
const embedded = new Set()
css = css.replace(/url\(fonts\/([\w-]+\.woff2)\)/g, (_m, file) => {
  const buf = readFileSync(path.join(fontsDir, file))
  embedded.add(file)
  return `url(data:font/woff2;base64,${buf.toString('base64')})`
})

// 3. Escape for a TS template literal.
const escaped = css.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

const header =
  '// AUTO-GENERATED by scripts/genKatexCss.mjs — DO NOT EDIT.\n' +
  '// Self-contained KaTeX stylesheet with embedded woff2 fonts (offline, CSP-safe).\n' +
  '// Regenerate after upgrading katex: node scripts/genKatexCss.mjs\n'

writeFileSync(outPath, `${header}export const KATEX_CSS = \`${escaped}\`\n`, 'utf8')
console.log(
  `Wrote ${path.relative(process.cwd(), outPath)} — ${(escaped.length / 1024).toFixed(0)} KB, ${embedded.size} fonts embedded`,
)
