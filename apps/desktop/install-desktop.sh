#!/usr/bin/env bash
# install-desktop.sh: put SlideBlaster in the desktop. Builds nothing; it installs
#   ~/.local/bin/slideblaster                      launcher (release build if present, else debug)
#   ~/.local/share/applications/slideblaster.desktop
#   ~/.local/share/icons/hicolor/256x256/apps/slideblaster.png
#   ~/.config/autostart/slideblaster.desktop       only with --autostart (starts hidden in the tray)
# The app embeds the editor and the core (see README.md for the build). The launcher points it at
# THIS repo's `sb` binary and hosts/web, which it uses only to compile figures and export PDF:
#   cabal build exe:sb
# `--uninstall` removes everything this script installs.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
web=$repo/hosts/web
tauri=$here/src-tauri
bin_dir=$HOME/.local/bin
apps=$HOME/.local/share/applications
icons=$HOME/.local/share/icons/hicolor/256x256/apps
auto=$HOME/.config/autostart

autostart=0 uninstall=0
for a in "$@"; do
  case $a in
    --autostart) autostart=1 ;;
    --uninstall) uninstall=1 ;;
    *) echo "usage: $0 [--autostart] [--uninstall]" >&2; exit 2 ;;
  esac
done

if [ "$uninstall" = 1 ]; then
  rm -f "$bin_dir/slideblaster" "$apps/slideblaster.desktop" "$icons/slideblaster.png" "$auto/slideblaster.desktop"
  update-desktop-database "$apps" 2>/dev/null || true
  echo "slideblaster: removed launcher, desktop entry, icon and autostart"
  exit 0
fi

# The sb binary of this repo.
sb=$(cd "$repo" && cabal list-bin exe:sb 2>/dev/null || true)
if [ -z "$sb" ] || [ ! -x "$sb" ]; then
  sb=$(find "$repo/dist-newstyle" -type f -name sb -perm -u+x 2>/dev/null | head -n 1 || true)
fi
[ -n "$sb" ] && [ -x "$sb" ] || { echo "no built sb binary: run 'cabal build exe:sb' in $repo" >&2; exit 1; }
[ -x "$tauri/target/release/slideblaster-desktop" ] || [ -x "$tauri/target/debug/slideblaster-desktop" ] \
  || { echo "no slideblaster-desktop binary: run 'cargo build' in $tauri" >&2; exit 1; }
[ -d "$web/dist" ] || echo "warning: $web/dist is missing; run 'npm run build' in $web" >&2

mkdir -p "$bin_dir" "$apps" "$icons"
cat >"$bin_dir/slideblaster" <<LAUNCHER
#!/usr/bin/env bash
# Generated by $here/install-desktop.sh
export SB_BIN="$sb"
export SB_WEB="$web"
app="$tauri/target/release/slideblaster-desktop"
[ -x "\$app" ] || app="$tauri/target/debug/slideblaster-desktop"
exec "\$app" "\$@"
LAUNCHER
chmod +x "$bin_dir/slideblaster"

cp "$tauri/icons/128x128@2x.png" "$icons/slideblaster.png"

entry() {  # entry EXEC-SUFFIX
  printf '[Desktop Entry]\nType=Application\nName=SlideBlaster\nComment=Edit and present slide decks\nExec=%s%s\nIcon=slideblaster\nTerminal=false\nCategories=Office;Presentation;\nStartupWMClass=slideblaster-desktop\n' "$bin_dir/slideblaster" "$1"
}
entry "" >"$apps/slideblaster.desktop"
if [ "$autostart" = 1 ]; then
  mkdir -p "$auto"
  { entry " --background"; echo "X-GNOME-Autostart-enabled=true"; } >"$auto/slideblaster.desktop"
fi
update-desktop-database "$apps" 2>/dev/null || true
gtk-update-icon-cache -q "$HOME/.local/share/icons/hicolor" 2>/dev/null || true
echo "slideblaster: launcher $bin_dir/slideblaster (sb: $sb), entry $apps/slideblaster.desktop"
[ "$autostart" = 1 ] && echo "autostart: $auto/slideblaster.desktop (tray only, --background)"
exit 0
