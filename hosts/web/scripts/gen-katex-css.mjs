// Generates src/generated/katex-inline-css.ts: the KaTeX stylesheet with its woff2 fonts
// embedded as data URIs (offline, CSP-safe). Port of editor/scripts/genKatexCss.mjs.
// Run automatically by `npm run build` and `npm run typecheck`; output is gitignored.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const dist = path.dirname(require.resolve("katex/dist/katex.min.css"));
let css = await readFile(path.join(dist, "katex.min.css"), "utf8");
const urls = [...css.matchAll(/url\((fonts\/[^)]+\.woff2)\)/g)].map((m) => m[1]);
for (const url of new Set(urls)) {
  const bytes = await readFile(path.join(dist, url));
  css = css.split(`url(${url})`).join(`url(data:font/woff2;base64,${bytes.toString("base64")})`);
}
// Only woff2 is embedded; drop the woff/ttf fallbacks so no external request can occur.
css = css.replace(/,url\(fonts\/[^)]+\.(?:woff|ttf)\) format\("(?:woff|truetype)"\)/g, "");
const out = path.resolve("src/generated/katex-inline-css.ts");
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, `// GENERATED by scripts/gen-katex-css.mjs. Do not edit.\nexport const KATEX_CSS = ${JSON.stringify(css)};\n`);
console.log(`katex css: ${(css.length / 1024).toFixed(0)} KiB`);
